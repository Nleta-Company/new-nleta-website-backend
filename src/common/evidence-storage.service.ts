
import {
  Injectable,
  InternalServerErrorException,
  Logger,
  NotFoundException,
} from '@nestjs/common';
import { randomUUID } from 'node:crypto';
import {
  mkdir,
  readFile,
  unlink,
  writeFile,
} from 'node:fs/promises';
import { basename, join, resolve } from 'node:path';

export type EvidenceUpload = {
  originalname: string;
  mimetype: string;
  size: number;
  buffer: Buffer;
};

export type SavedEvidence = {
  originalName: string;
  storageKey: string;
  mimeType: string;
  sizeBytes: number;
};

@Injectable()
export class EvidenceStorageService {
  private readonly logger = new Logger(EvidenceStorageService.name);

  private readonly storageDirectory = resolve(
    process.cwd(),
    'private-evidence',
  );

  private readonly allowedTypes: Record<string, string> = {
    'image/jpeg': '.jpg',
    'image/png': '.png',
    'image/webp': '.webp',
    'application/pdf': '.pdf',
  };

  async saveFiles(files: EvidenceUpload[]): Promise<SavedEvidence[]> {
    await mkdir(this.storageDirectory, { recursive: true });

    const saved: SavedEvidence[] = [];

    try {
      for (const file of files) {
        const extension = this.allowedTypes[file.mimetype];

        if (!extension) {
          throw new Error('Unsupported evidence file type.');
        }

        const storageKey = `${randomUUID()}${extension}`;
        const destination = join(this.storageDirectory, storageKey);

        await writeFile(destination, file.buffer, { flag: 'wx' });

        saved.push({
          originalName: file.originalname.slice(0, 255),
          storageKey,
          mimeType: file.mimetype,
          sizeBytes: file.size,
        });
      }

      return saved;
    } catch (error) {
      await Promise.all(
        saved.map((file) =>
          unlink(join(this.storageDirectory, file.storageKey)).catch(
            () => undefined,
          ),
        ),
      );

      this.logger.error('Evidence storage operation failed.');

      throw new InternalServerErrorException(
        'Evidence files could not be saved.',
      );
    }
  }

  async readFile(storageKey: string): Promise<Buffer> {
    // Only accept UUID-based filenames generated by saveFiles().
    if (
      !/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|png|webp|pdf)$/i.test(
        basename(storageKey),
      )
    ) {
      throw new NotFoundException('Evidence file not found.');
    }

    try {
      return await readFile(join(this.storageDirectory, storageKey));
    } catch {
      throw new NotFoundException(
        'Evidence file not found or no longer available.',
      );
    }
  }
}
